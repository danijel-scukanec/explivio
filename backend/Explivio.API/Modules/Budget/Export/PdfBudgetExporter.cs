using System.Globalization;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Explivio.API.Modules.Budget.Export;

// F25: PDF export via QuestPDF. A clean one-page report: title, per-expense table, category summary
// and the grand total — all in the trip's base currency. The Community license is enabled once at
// startup (Program.cs).
public sealed class PdfBudgetExporter : IBudgetExporter
{
    public ExportFormat Format => ExportFormat.Pdf;

    public (byte[] Content, string ContentType, string FileName) Export(string tripName, BudgetSummaryResponse summary)
    {
        var bytes = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Margin(40);
                page.Size(PageSizes.A4);
                page.DefaultTextStyle(x => x.FontSize(10));

                page.Header().Column(col =>
                {
                    col.Item().Text(tripName).FontSize(18).SemiBold();
                    col.Item().Text($"Budget summary · base currency {summary.BaseCurrency}")
                        .FontSize(11).FontColor(Colors.Grey.Darken1);
                    if (!summary.ConversionAvailable)
                    {
                        col.Item().PaddingTop(4).Text(
                            "Live exchange rates were unavailable — some amounts are shown in their original currency.")
                            .FontSize(8).FontColor(Colors.Red.Medium);
                    }
                });

                page.Content().PaddingVertical(12).Column(col =>
                {
                    col.Spacing(16);

                    // Expense table
                    col.Item().Table(table =>
                    {
                        table.ColumnsDefinition(c =>
                        {
                            c.ConstantColumn(70);   // date
                            c.RelativeColumn();      // description
                            c.ConstantColumn(80);   // category
                            c.ConstantColumn(90);   // original
                            c.ConstantColumn(90);   // in base
                        });

                        table.Header(header =>
                        {
                            HeaderCell(header, "Date");
                            HeaderCell(header, "Description");
                            HeaderCell(header, "Category");
                            HeaderCell(header, "Amount");
                            HeaderCell(header, $"In {summary.BaseCurrency}");
                        });

                        foreach (var e in summary.Expenses)
                        {
                            BodyCell(table, e.Date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture));
                            BodyCell(table, e.Description);
                            BodyCell(table, e.Category.ToString());
                            BodyCell(table, $"{e.Amount.ToString("N2", CultureInfo.InvariantCulture)} {e.Currency}");
                            BodyCell(table, e.AmountInBase is { } b
                                ? b.ToString("N2", CultureInfo.InvariantCulture)
                                : "—");
                        }
                    });

                    // Category summary
                    col.Item().Text("By category").FontSize(12).SemiBold();
                    col.Item().Table(table =>
                    {
                        table.ColumnsDefinition(c =>
                        {
                            c.RelativeColumn();
                            c.ConstantColumn(100);
                        });
                        foreach (var cat in summary.ByCategory)
                        {
                            BodyCell(table, cat.Category);
                            BodyCell(table, $"{cat.Total.ToString("N2", CultureInfo.InvariantCulture)} {summary.BaseCurrency}");
                        }
                    });

                    col.Item().AlignRight().Text(
                        $"Total: {summary.Total.ToString("N2", CultureInfo.InvariantCulture)} {summary.BaseCurrency}")
                        .FontSize(13).Bold();
                });

                page.Footer().AlignCenter().Text(x =>
                {
                    x.Span("Generated by Explivio · ");
                    x.Span(DateTime.UtcNow.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture));
                });
            });
        }).GeneratePdf();

        var fileName = $"{Slug(tripName)}-budget.pdf";
        return (bytes, "application/pdf", fileName);
    }

    private static void HeaderCell(TableCellDescriptor header, string text) =>
        header.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten1)
            .PaddingVertical(4).Text(text).SemiBold();

    private static void BodyCell(TableDescriptor table, string text) =>
        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3)
            .PaddingVertical(3).Text(text);

    private static string Slug(string value)
    {
        var chars = value.Trim().ToLowerInvariant()
            .Select(c => char.IsLetterOrDigit(c) ? c : '-')
            .ToArray();
        var slug = new string(chars).Trim('-');
        while (slug.Contains("--")) slug = slug.Replace("--", "-");
        return string.IsNullOrEmpty(slug) ? "trip" : slug;
    }
}
