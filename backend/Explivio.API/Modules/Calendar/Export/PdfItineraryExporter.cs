using System.Globalization;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Explivio.API.Modules.Calendar.Export;

// F27: a printable day-by-day itinerary via QuestPDF (the Community license is enabled once at
// startup, Program.cs — set for F25). Events are grouped by date; each row shows its time (or
// "All day"), a kind badge, the title, location and description.
public sealed class PdfItineraryExporter : IItineraryExporter
{
    public ItineraryExportFormat Format => ItineraryExportFormat.Pdf;

    public (byte[] Content, string ContentType, string FileName) Export(ItineraryDocument document)
    {
        var days = document.Events
            .GroupBy(e => e.Date)
            .OrderBy(g => g.Key)
            .ToList();

        var bytes = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Margin(40);
                page.Size(PageSizes.A4);
                page.DefaultTextStyle(x => x.FontSize(10));

                page.Header().Column(col =>
                {
                    col.Item().Text(document.TripName).FontSize(18).SemiBold();
                    var subtitle = string.IsNullOrWhiteSpace(document.Destination)
                        ? DateRange(document)
                        : $"{document.Destination} · {DateRange(document)}";
                    col.Item().Text(subtitle).FontSize(11).FontColor(Colors.Grey.Darken1);
                });

                page.Content().PaddingVertical(12).Column(col =>
                {
                    col.Spacing(14);

                    if (days.Count == 0)
                    {
                        col.Item().Text("No activities or reservations planned yet.")
                            .FontColor(Colors.Grey.Medium).Italic();
                    }

                    foreach (var day in days)
                    {
                        col.Item().Column(dayCol =>
                        {
                            dayCol.Spacing(6);
                            dayCol.Item().BorderBottom(1).BorderColor(Colors.Grey.Lighten1).PaddingBottom(3)
                                .Text(day.Key.ToString("dddd, d MMM yyyy", CultureInfo.InvariantCulture))
                                .FontSize(12).SemiBold();

                            foreach (var e in day)
                            {
                                dayCol.Item().Row(row =>
                                {
                                    row.ConstantItem(70).Text(TimeLabel(e))
                                        .FontColor(Colors.Grey.Darken1);
                                    row.RelativeItem().Column(info =>
                                    {
                                        info.Item().Text(text =>
                                        {
                                            text.Span(e.Summary).SemiBold();
                                            text.Span($"  [{e.Kind}]").FontSize(8).FontColor(Colors.Grey.Medium);
                                        });
                                        if (!string.IsNullOrWhiteSpace(e.Location))
                                            info.Item().Text(e.Location).FontSize(9).FontColor(Colors.Grey.Darken1);
                                        if (!string.IsNullOrWhiteSpace(e.Description))
                                            info.Item().Text(e.Description).FontSize(9).FontColor(Colors.Grey.Darken2);
                                    });
                                });
                            }
                        });
                    }
                });

                page.Footer().AlignCenter().Text(x =>
                {
                    x.Span("Generated by Explivio · ");
                    x.Span(DateTime.UtcNow.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture));
                });
            });
        }).GeneratePdf();

        var fileName = $"{Slug(document.TripName)}-itinerary.pdf";
        return (bytes, "application/pdf", fileName);
    }

    private static string TimeLabel(CalendarEvent e) =>
        e.AllDay || e.Start is null
            ? "All day"
            : e.Start.Value.ToString("HH:mm", CultureInfo.InvariantCulture);

    private static string DateRange(ItineraryDocument d) =>
        $"{d.StartDate.ToString("d MMM yyyy", CultureInfo.InvariantCulture)} – {d.EndDate.ToString("d MMM yyyy", CultureInfo.InvariantCulture)}";

    private static string Slug(string value)
    {
        var chars = value.Trim().ToLowerInvariant()
            .Select(c => char.IsLetterOrDigit(c) ? c : '-')
            .ToArray();
        var slug = new string(chars).Trim('-');
        while (slug.Contains("--")) slug = slug.Replace("--", "-");
        return string.IsNullOrEmpty(slug) ? "trip" : slug;
    }
}
